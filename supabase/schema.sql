-- The app uses its own server-side cookie sessions and password hashes (not Supabase Auth).
-- Keep all tables inaccessible to browser roles; a trusted server connection must perform
-- all reads/writes. Supabase service_role bypasses RLS and must remain server-only.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'users', 'sessions', 'assets', 'watchlists', 'positions', 'orders',
    'cash_transactions', 'transfer_methods', 'transfer_requests',
    'announcements', 'settings', 'audit_log'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon, authenticated', table_name);
  end loop;
end
$$;

grant all on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to service_role;

commit;
